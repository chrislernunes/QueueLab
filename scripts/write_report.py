#!/usr/bin/env python3
"""Write reports/execution_research.md from engine outputs. No invented numbers."""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import analysis


def fmt(x, digits=4) -> str:
    if x is None:
        return ""
    try:
        return f"{float(x):.{digits}f}"
    except (TypeError, ValueError):
        return str(x)


def main() -> int:
    sens = analysis.sensitivity()
    div = analysis.executions(analysis.DIVERGENCE)
    q = analysis.quality()
    meta = analysis.summary()
    bench = analysis.benchmark()
    marks = analysis.markouts()
    if not q.get("synthetic", False):
        label = "The session dataset is not flagged synthetic. Treat it as a capture, not as ground-truth queue position."
    else:
        label = "The session dataset is synthetic. It is not a Binance recording and it is not evidence of live fill probability."
    fill_span = float(sens.groupby("submit_delay_us")["fill_rate"].agg(lambda s: s.max() - s.min()).max())
    lines = []
    a = lines.append
    a("# Execution research notes")
    a("")
    a("Generated by `scripts/write_report.py` from the CSV and JSON files in `reports/`.")
    a("If those files change, regenerate this note. Do not hand-edit the numbers.")
    a("")
    a("## Question")
    a("")
    a("How sensitive are passive-order fill probability, execution cost and adverse selection to queue-position assumptions and order-entry latency?")
    a("")
    a("## What was actually run")
    a("")
    a(label)
    a("")
    a(f"- Dataset: `{meta['dataset']}`")
    a(f"- SHA-256: `{meta['dataset_sha256']}`")
    a(f"- Symbol field: `{meta['symbol']}` (synthetic flag `{meta['synthetic']}`)")
    a(f"- Git commit recorded by the engine: `{meta['git']}`")
    a(f"- Intents: {meta['n_intents']}")
    a(f"- Fee: {meta['fee_ppm']} ppm. {meta['fee_note']}")
    a(f"- Latency grid: {meta['latency_note']}")
    a(f"- Queue models: {meta['queue_note']}")
    a(f"- Bootstrap: {meta['bootstrap']} ({meta['bootstrap_samples']} resamples).")
    a(f"- Book hash after replay: `{meta['book_hash']}`")
    a(f"- Data-quality ok: {meta['data_quality_ok']}. Gaps: {q.get('gaps')}. Duplicates: {q.get('duplicates')}. Crossed observations: {q.get('crossed_observations')}.")
    a(f"- Event counts: `{q.get('counts')}`.")
    a("")
    a("Decision prices use the book visible at release. Later mids are used only for markouts.")
    a("Submit delays are scenario assumptions. They were not measured on a Binance path.")
    a("")
    a("## Session result")
    a("")
    a("Prices below are integer price units. On this fixture `price_scale` is 2, so one unit is 0.01 of the quote currency. Quantities use `qty_scale` 4. The instrument is a scenario assumption, not a live `exchangeInfo` response.")
    a("")
    a("Fill rate is the fraction of accepted orders with `filled_qty > 0`. The interval is a circular block bootstrap of that indicator, percentile 2.5/97.5, block length `floor(sqrt(n))`. It does not claim correct coverage for every dependence structure.")
    a("")
    a("| model | submit delay µs | n | filled | fill rate | CI low | CI high | mean filled qty | mean spread capture | mean IS | mean markout |")
    a("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for row in sens.sort_values(["model", "submit_delay_us"]).itertuples(index=False):
        a(
            f"| {row.model} | {int(row.submit_delay_us)} | {int(row.n_accepted)} | {int(row.n_filled)} | "
            f"{fmt(row.fill_rate)} | {fmt(row.fill_rate_ci_lo)} | {fmt(row.fill_rate_ci_hi)} | "
            f"{fmt(row.mean_filled_qty)} | {fmt(row.mean_spread_capture)} | "
            f"{fmt(row.mean_implementation_shortfall)} | {fmt(row.mean_markout)} |"
        )
    a("")
    a(f"Largest fill-rate gap across queue models at a fixed submit delay: {fill_span:.4f}.")
    if fill_span < 0.01:
        a("")
        a("On this synthetic session the three queue models do not separate fill rates. That is a property of the generator: many fills are trade-throughs or consume the whole displayed level, so the unexplained-cancel rule is not the binding constraint. It is not a hidden bug, and it is not a claim that the models agree on real Binance flow.")
    a("")
    a("Mean markout is the pooled mean of signed post-fill mid changes across the configured horizons. Positive means the mid moved in the order's favor. Overlapping orders are dependent. The table is descriptive.")
    a("")
    a(f"Signed markout sample size (fill × horizon rows, including nulls if any): {len(marks)}.")
    a(f"Median of non-null signed markouts, descriptive SciPy percentile, not a second confidence interval: {analysis.descriptive_percentile(marks['signed_markout'], 50):.4f} price units.")
    a("")
    a("Spread capture at a buy is `mid_at_fill - price`. Implementation shortfall at a buy is `price - decision_mid`. Positive spread capture is not net P&L. Fees are in the ledger, not added again inside these two columns. See `docs/assumptions_and_limitations.md`.")
    a("")
    a("## Constructed disagreement")
    a("")
    a("File `data/processed/synthetic/divergence` is a five-event scenario built so the cancellation rules can disagree. It is not a sample from a market.")
    a("")
    a("| model | filled_qty | status | n_fills |")
    a("|---|---:|---|---:|")
    for row in div.sort_values("model").itertuples(index=False):
        a(f"| {row.model} | {int(row.filled_qty)} | {row.status} | {int(row.n_fills)} |")
    a("")
    a("Read this next to the session table. The unit scenario is where the models are forced apart. The session is where, under this generator, they are not.")
    a("")
    a("## Benchmark")
    a("")
    a("Command: `QUEUELAB_PROFILE=release dune exec --profile release queuelab -- benchmark --dataset data/processed/synthetic/session --synthetic-events 200000 --out reports/bench.json`.")
    a("")
    a(f"- Machine: {bench['uname']}, {bench['cpu']}, {bench['meminfo'].strip()}")
    a(f"- OCaml: {bench['ocaml']}")
    a(f"- Profile field: {bench['profile']}")
    a(f"- Dataset events: {bench['dataset_events']} (synthetic={bench['dataset_synthetic']})")
    a(f"- Dataset replay median: {bench['dataset_replay']['median_s']:.6f} s over {bench['dataset_replay']['repeats']} repeats after one warmup")
    a(f"- Synthetic events: {bench['synthetic_events']} from {bench['synthetic_steps']} steps")
    a(f"- Synthetic replay median: {bench['synthetic_replay']['median_s']:.6f} s")
    a(f"- Median events/second on that synthetic replay: {bench['events_per_second_synthetic_median']:.1f}")
    a(f"- JSON roundtrip of 20k copies of one event, median: {bench['json_roundtrip_20k']['median_s']:.6f} s")
    a(f"- One probabilistic order over the synthetic stream, median: {bench['queue_sim_one_order_synthetic']['median_s']:.6f} s")
    a(f"- Checkpoint roundtrip median: {bench['checkpoint_roundtrip_synthetic']['median_s']:.6e} s")
    a("")
    a("The checkpoint time is the final book, which in this generator is a handful of price levels, not a serialization of the event log. Do not quote it as the cost of checkpointing a deep book. Do not quote the events/second figure for other hardware, compilers, or profiles.")
    a("")
    a("## What this does not show")
    a("")
    a("- No live Binance depth is in the committed dataset. Public historical dumps do not include the incremental depth required to rebuild this book. A capture has to be taken prospectively and is not redistributed here.")
    a("- Queue position is not observed. Model differences are assumptions.")
    a("- Latency numbers in the grid are not measured round-trip times.")
    a("- The fee is 100 ppm in the session config, not a Binance fee-tier lookup.")
    a("- Positive spread capture can coexist with negative markout. The table shows both.")
    a("")
    a("## Capture attempt")
    a("")
    attempt = analysis.ROOT / "reports" / "capture_attempt.json"
    if attempt.is_file():
        rec = json.loads(attempt.read_text())
        a(f"Command: `{rec['command']}`")
        a("")
        a(rec["result"])
        a("")
        a(rec["interpretation"])
    else:
        a("No `reports/capture_attempt.json` is present. Absence of that file is not a successful capture.")
    a("")
    path = analysis.ROOT / "reports" / "execution_research.md"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
